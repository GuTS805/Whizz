// Copies the compiled Whizz ABI into the web app as a typed TS constant,
// so the frontend gets autocomplete + type-checking for every contract call.
// Run after changing the contract:  npm run export-abi
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = import.meta.dirname;
const artifactPath = path.join(root, "../artifacts/contracts/Whizz.sol/Whizz.json");
const outPath = path.join(root, "../../web/src/lib/abi.ts");

const { abi } = JSON.parse(await readFile(artifactPath, "utf8"));
await mkdir(path.dirname(outPath), { recursive: true });
await writeFile(
  outPath,
  `// AUTO-GENERATED by contracts/scripts/export-abi.ts — do not edit by hand.\n` +
    `export const whizzAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`ABI written to ${path.relative(process.cwd(), outPath)}`);
